/* ---------- 선택 사양 적용 ----------
   FZ.SEL.hz: 60(국내 기본) | 50, FZ.SEL.spec[제품id]: 선택한 모델 인덱스 */
FZ.SEL = { hz: 60, spec: {}, manual: {} };
(function () {
  // 사양 1행 → 객체 (요청 주파수 값이 없으면 있는 쪽 사용)
  FZ.specOf = function (pid, idx, hz) {
    const S = FZ.SPECS[pid];
    if (!S) return null;
    const i = idx == null ? (FZ.SEL.spec[pid] ?? S.def) : idx;
    const r = S.rows[Math.max(0, Math.min(S.rows.length - 1, i))];
    const want = hz || FZ.SEL.hz;
    let v = want === 50 ? r[4] : r[5], usedHz = want;
    if (!v) { v = want === 50 ? r[5] : r[4]; usedHz = want === 50 ? 60 : 50; }
    const perf = !!v; if (!v) { v = [null, null, null, null]; usedHz = want; } // 부속: 성능 수치 없음
    return { idx: i, model: r[0], impeller: r[1], phase: r[2], poles: r[3], airflow: v[0], power: v[1], current: v[2], pressure: v[3], weight: r[6], hz: usedHz, hzNote: perf && usedHz !== want, has50: !!r[4], has60: !!r[5], perf, ov: r[7] || null, src: S.src };
  };
  // 선택 사양을 반영한 제품 정보 (계산·배치·화면 공용)
  FZ.eff = function (pid, idx) {
    const p = FZ.PRODUCTS[pid], s = FZ.specOf(pid, idx);
    if (!s) return p;
    const S = FZ.SPECS[pid], base = S.rows[S.def][1];
    const o = s.ov || {}; // 모델별 덮어쓰기 (3D 종류·설치 위치)
    return {
      ...p, model: s.model, airflow: s.airflow != null ? s.airflow : p.airflow, power: s.power != null ? s.power : p.power,
      pressure: s.pressure != null ? s.pressure + 'mmAq' : p.pressure,
      size: p.size * (s.impeller && base ? s.impeller / base : 1),
      model3d: o.m3d || p.model3d, mount: o.mount || p.mount,
      spec: s
    };
  };
  FZ.specCount = pid => (FZ.SPECS[pid] ? FZ.SPECS[pid].rows.length : 1);
})();
